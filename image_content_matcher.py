"""
    Модуль для проверки соответствия изображений контенту статьи через DeepSeek AI
    
    Использует DeepSeek AI для анализа соответствия изображения контенту статьи
    и проверки уникальности изображений между постами.
    
    Автор: VR-Lounge
"""

import os
import requests
import json
from pathlib import Path
from typing import List, Dict, Tuple, Optional

DEEPSEEK_API_KEY = os.getenv('DEEPSEEK_API_KEY')

def проверить_соответствие_изображения_строго_через_deepseek(
    url_изображения: str,
    alt_текст: str,
    заголовок_статьи: str,
    текст_статьи: str
) -> Tuple[bool, float, str]:
    """Строгая проверка изображения через DeepSeek (жёсткие условия)."""
    if not DEEPSEEK_API_KEY:
        return True, 0.5, "DeepSeek не настроен, пропускаем строгую проверку"
    
    try:
        url = "https://api.deepseek.com/v1/chat/completions"
        headers = {
            "Content-Type": "application/json",
            "Authorization": f"Bearer {DEEPSEEK_API_KEY}"
        }
        
        system_prompt = """Ты очень строгий редактор фитнес‑контента.
Нужно допускать только изображения без логотипов, баннеров, надписей и рекламных элементов.
Подходят только чистые фото фитнеса/тренировок/питания, напрямую связанные с текстом статьи.

Формат ответа (строго JSON):
{
  "соответствует": true/false,
  "оценка": 0.0-1.0,
  "объяснение": "краткое объяснение на русском",
  "есть_логотип": true/false,
  "есть_текст_на_изображении": true/false,
  "релевантность_контенту": "высокая/средняя/низкая"
}

ЕСЛИ есть логотип ИЛИ текст ИЛИ релевантность не высокая — вернуть "соответствует": false."""
        
        user_prompt = f"""Заголовок статьи: {заголовок_статьи}
Текст статьи (фрагмент): {текст_статьи[:1200]}
Alt/Title: {alt_текст or 'нет'}
URL изображения: {url_изображения}"""
        
        data = {
            "model": "deepseek-chat",
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt}
            ],
            "temperature": 0.1,
            "max_tokens": 200,
            "response_format": {"type": "json_object"}
        }
        
        response = requests.post(url, headers=headers, json=data, timeout=30)
        response.raise_for_status()
        result = response.json()
        ответ = result['choices'][0]['message']['content']
        
        анализ = json.loads(ответ)
        соответствует = анализ.get('соответствует', False)
        оценка = float(анализ.get('оценка', 0.0))
        объяснение = анализ.get('объяснение', 'Строгая проверка')
        есть_логотип = анализ.get('есть_логотип', False)
        есть_текст = анализ.get('есть_текст_на_изображении', False)
        релевантность = анализ.get('релевантность_контенту', 'низкая')
        
        if есть_логотип or есть_текст or релевантность != 'высокая':
            return False, 0.0, "Строгий фильтр: логотип/текст/низкая релевантность"
        
        return соответствует and оценка >= 0.7, оценка, объяснение
    except Exception as e:
        print(f"⚠️ Ошибка строгой проверки через DeepSeek: {e}")
        return False, 0.0, f"Ошибка строгой проверки: {str(e)[:50]}"

def проверить_изображение_в_два_этапа(
    url_изображения: str,
    alt_текст: str,
    заголовок_статьи: str,
    текст_статьи: str
) -> Tuple[bool, float, str]:
    """Двухэтапный контроль качества изображения."""
    ok1, score1, exp1 = проверить_соответствие_изображения_контенту_через_deepseek(
        url_изображения, alt_текст, заголовок_статьи, текст_статьи
    )
    if not ok1:
        return False, 0.0, f"Этап 1: {exp1}"
    
    ok2, score2, exp2 = проверить_соответствие_изображения_строго_через_deepseek(
        url_изображения, alt_текст, заголовок_статьи, текст_статьи
    )
    if not ok2:
        return False, 0.0, f"Этап 2: {exp2}"
    
    return True, max(score1, score2), exp2

def проверить_соответствие_изображения_контенту_через_deepseek(
    url_изображения: str,
    alt_текст: str,
    заголовок_статьи: str,
    текст_статьи: str
) -> Tuple[bool, float, str]:
    """
    Проверяет соответствие изображения контенту статьи через DeepSeek AI
    
    Args:
        url_изображения: URL изображения
        alt_текст: Alt текст изображения
        заголовок_статьи: Заголовок статьи
        текст_статьи: Текст статьи (первые 1000 символов)
    
    Returns:
        (соответствует, оценка_релевантности, объяснение)
        - соответствует: True если изображение соответствует контенту
        - оценка_релевантности: от 0.0 до 1.0
        - объяснение: краткое объяснение соответствия
    """
    if not DEEPSEEK_API_KEY:
        # Если DeepSeek не настроен, возвращаем True (не блокируем)
        return True, 0.5, "DeepSeek не настроен, пропускаем проверку"
    
    try:
        url = "https://api.deepseek.com/v1/chat/completions"
        
        headers = {
            "Content-Type": "application/json",
            "Authorization": f"Bearer {DEEPSEEK_API_KEY}"
        }
        
        system_prompt = """Ты эксперт по анализу соответствия изображений контенту статей о фитнесе и здоровье.

Твоя задача: проанализировать, соответствует ли изображение (по его описанию/alt тексту) контенту статьи.

Формат ответа (строго JSON):
{
  "соответствует": true/false,
  "оценка": 0.0-1.0,
  "объяснение": "краткое объяснение на русском (1-2 предложения)",
  "есть_логотип": true/false,
  "есть_текст_на_изображении": true/false,
  "релевантность_контенту": "высокая/средняя/низкая"
}

КРИТИЧЕСКИ ВАЖНЫЕ КРИТЕРИИ:
1. НЕТ ЛОГОТИПОВ И ТЕКСТА НА ИЗОБРАЖЕНИИ:
   - Если на изображении есть логотипы, надписи, текст, буквы, названия организаций, подкастов - верни "есть_логотип": true или "есть_текст_на_изображении": true
   - Такие изображения НЕ подходят для блога о фитнесе
   - Нужны ЧИСТЫЕ фотографии людей, занимающихся фитнесом, без текста и логотипов

2. РЕЛЕВАНТНОСТЬ КОНТЕНТУ:
   - Изображение должно отражать тему статьи (тренировки, питание, мотивация)
   - Для статей про силовые тренировки - изображения с весами, тренажерами, людьми в процессе тренировки
   - Для статей про питание - изображения с едой, продуктами
   - Для статей про мотивацию - вдохновляющие изображения людей в фитнесе
   - Избегай общих/декоративных изображений, не связанных с темой

3. КАЧЕСТВО ИЗОБРАЖЕНИЯ:
   - Предпочтительны фотографии девушек и мужчин, которые занимаются фитнесом
   - Изображения должны показывать процесс тренировки, упражнения, активность
   - Избегай статичных портретов, головок, простых фотографий людей без контекста фитнеса

Будь ОЧЕНЬ строгим: если изображение содержит логотипы, текст, надписи, или не соответствует теме - верни "соответствует": false."""
        
        user_prompt = f"""Заголовок статьи: {заголовок_статьи}

Текст статьи (первые 1000 символов): {текст_статьи[:1000]}

Описание изображения (alt текст): {alt_текст or 'нет описания'}

URL изображения: {url_изображения[:100]}

Проанализируй соответствие изображения контенту статьи. Верни только JSON без дополнительного текста."""
        
        data = {
            "model": "deepseek-chat",
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt}
            ],
            "temperature": 0.3,  # Низкая температура для более точного анализа
            "max_tokens": 200,
            "response_format": {"type": "json_object"}
        }
        
        response = requests.post(url, headers=headers, json=data, timeout=30)
        response.raise_for_status()
        
        result = response.json()
        ответ = result['choices'][0]['message']['content']
        
        # Парсим JSON ответ
        try:
            анализ = json.loads(ответ)
            соответствует = анализ.get('соответствует', True)
            оценка = float(анализ.get('оценка', 0.5))
            объяснение = анализ.get('объяснение', 'Проверка выполнена')
            есть_логотип = анализ.get('есть_логотип', False)
            есть_текст = анализ.get('есть_текст_на_изображении', False)
            
            # КРИТИЧЕСКАЯ ПРОВЕРКА: Если есть логотип или текст - автоматически отклоняем
            if есть_логотип or есть_текст:
                print(f"  ❌ Изображение отклонено: обнаружен логотип или текст на изображении")
                print(f"     Логотип: {есть_логотип}, Текст: {есть_текст}")
                return False, 0.0, f"Изображение содержит логотип или текст (не подходит для блога)"
            
            # ДОПОЛНИТЕЛЬНАЯ ПРОВЕРКА: Проверяем alt/title текст на наличие признаков подкастов, логотипов
            alt_нижний = (alt_текст or '').lower()
            if any(маркер in alt_нижний for маркер in ['podcast', 'episode', 'logo', 'training science', 'the training science']):
                print(f"  ❌ Изображение отклонено: alt/title содержит признаки подкаста/логотипа")
                return False, 0.0, f"Изображение связано с подкастом/логотипом (не подходит для блога)"
            
            return соответствует, оценка, объяснение
        except (json.JSONDecodeError, ValueError, KeyError):
            # Если не удалось распарсить, считаем что соответствует
            return True, 0.5, "Ошибка парсинга ответа DeepSeek"
    
    except Exception as e:
        print(f"⚠️ Ошибка проверки соответствия через DeepSeek: {e}")
        # При ошибке не блокируем, но логируем
        return True, 0.5, f"Ошибка: {str(e)[:50]}"

def выбрать_лучшее_изображение_для_контента(
    список_изображений: List[Dict],
    заголовок_статьи: str,
    текст_статьи: str,
    существующие_изображения: List[str] = None,
    исключить_urls: List[str] = None,
    начальный_индекс: int = 0,
    строгий_фильтр: bool = True
) -> Optional[Dict]:
    """
    Выбирает лучшее изображение из списка на основе соответствия контенту
    
    Args:
        список_изображений: Список словарей с url, alt, title
        заголовок_статьи: Заголовок статьи
        текст_статьи: Текст статьи
        существующие_изображения: Список URL изображений, уже использованных в других постах
        исключить_urls: Дополнительный список URL для исключения (например, использованные в текущей сессии)
        начальный_индекс: Начальный индекс для выбора изображения (для разнообразия при одинаковых оценках)
    
    Returns:
        Лучшее изображение (словарь) или None
    """
    if not список_изображений:
        return None
    
    if существующие_изображения is None:
        существующие_изображения = []
    if исключить_urls is None:
        исключить_urls = []
    
    # Объединяем все исключаемые URL
    все_исключаемые = list(существующие_изображения) + list(исключить_urls)
    
    # Фильтруем изображения, которые уже используются в других постах или в текущей сессии
    уникальные_изображения = []
    for img in список_изображений:
        img_url = img.get('url', '')
        if not img_url:
            continue
        
        # Нормализуем URL для сравнения
        normalized_url = img_url.split('?')[0].lower()
        
        # Проверяем, не используется ли это изображение
        используется = False
        for existing_url in все_исключаемые:
            if normalized_url == existing_url.split('?')[0].lower():
                используется = True
                break
        
        if not используется:
            уникальные_изображения.append(img)
    
    if not уникальные_изображения:
        print("⚠️ Все изображения уже используются в других постах")
        # Если все изображения уже используются, берем первое (но это не идеально)
        return список_изображений[0] if список_изображений else None
    
    # Оцениваем каждое уникальное изображение через DeepSeek
    оценки_изображений = []
    for img in уникальные_изображения[:10]:  # Увеличиваем до 10 для большего разнообразия
        img_url = img.get('url', '')
        alt_текст = img.get('alt', '') or img.get('title', '')
        
        соответствует, оценка, объяснение = проверить_изображение_в_два_этапа(
            img_url, alt_текст, заголовок_статьи, текст_статьи
        )
        
        оценки_изображений.append({
            'изображение': img,
            'соответствует': соответствует,
            'оценка': оценка,
            'объяснение': объяснение
        })
        
        print(f"  📊 Изображение {img_url[:50]}...: оценка {оценка:.2f}, соответствует={соответствует}")
        if объяснение:
            print(f"     {объяснение}")
    
    # Сортируем по оценке (лучшие первыми)
    оценки_изображений.sort(key=lambda x: x['оценка'], reverse=True)
    
    # Проверяем, все ли изображения имеют одинаковую оценку (например, 0.50 когда DeepSeek не настроен)
    все_одинаковые_оценки = len(оценки_изображений) > 0 and all(
        abs(оценка['оценка'] - оценки_изображений[0]['оценка']) < 0.01
        for оценка in оценки_изображений
    )
    
    # Если все оценки одинаковые, используем индекс для разнообразия
    if все_одинаковые_оценки and len(оценки_изображений) > 1:
        # Фильтруем только те, которые соответствуют контенту
        соответствующие = [о for о in оценки_изображений if о['соответствует']]
        if соответствующие:
            idx = начальный_индекс % len(соответствующие)
            выбранное = соответствующие[idx]
            print(f"✅ Выбрано изображение по индексу {idx} (все оценки одинаковые): оценка {выбранное['оценка']:.2f}")
            return выбранное['изображение']
    
    # Выбираем лучшее изображение, которое соответствует контенту
    for оценка_данные in оценки_изображений:
        if оценка_данные['соответствует']:
            print(f"✅ Выбрано лучшее изображение: оценка {оценка_данные['оценка']:.2f}")
            return оценка_данные['изображение']
    
    # Если ни одно не соответствует — в строгом режиме отклоняем
    if строгий_фильтр:
        print("❌ Строгий фильтр: нет подходящих изображений без логотипов/текста")
        return None
    
    # В нестрогом режиме берем лучшее по оценке
    if оценки_изображений:
        print(f"⚠️ Выбрано изображение с наилучшей оценкой: {оценки_изображений[0]['оценка']:.2f}")
        return оценки_изображений[0]['изображение']
    
    # Если нет оценок (DeepSeek не настроен), возвращаем уникальное по индексу для разнообразия
    if уникальные_изображения:
        idx = начальный_индекс % len(уникальные_изображения)
        print(f"⚠️ DeepSeek не настроен, возвращаю уникальное изображение (индекс {idx})")
        return уникальные_изображения[idx]
    
    return None

def получить_использованные_изображения_из_постов(
    существующие_посты: List[Dict],
    *,
    recent_limit: int = 80,
) -> List[str]:
    """
    URL изображений из недавних постов (анти-повтор в ленте).

    Берём только последние recent_limit постов по date — иначе сток Fitness|Woman
    (131 шт.) быстро «исчерпывается» на всём архиве и публикация останавливается.
    """
    использованные_urls = []
    if not существующие_посты:
        return использованные_urls

    try:
        упорядоченные = sorted(
            существующие_посты,
            key=lambda p: str(p.get('date') or ''),
            reverse=True,
        )
    except Exception:
        упорядоченные = list(существующие_посты)

    for пост in упорядоченные[: max(1, int(recent_limit))]:
        главное_изображение = пост.get('image', '')
        if главное_изображение:
            использованные_urls.append(главное_изображение)

        for img_dict in пост.get('images', []) or []:
            img_url = img_dict.get('url', '') if isinstance(img_dict, dict) else ''
            if img_url:
                использованные_urls.append(img_url)

    return использованные_urls
